const CACHE = new Map<string, number[]>();

function decode(key: string, pattern: string): number[] {
  const rows = pattern.split("/");
  if (rows.length !== GLYPH_H || rows.some((row) => !/^[#.]{5}$/.test(row))) {
    throw new Error(`malformed glyph for ${JSON.stringify(key)}`);
  }
  return rows.map((row) => parseInt(row.replace(/#/g, "1").replace(/\./g, "0"), 2));
}

/** The glyph keys the table defines (the tests check each one decodes). */
export const GLYPH_KEYS: string[] = Object.keys(ROWS);

/** Seven row bitmasks for one character (bit 4 is the leftmost cell). */
export function glyph(ch: string): number[] {
  const first = Array.from(ch.normalize("NFD"))[0] ?? "?";
  const upper = Array.from(first.toUpperCase())[0] ?? "?";
  const key = Object.hasOwn(ROWS, upper) ? upper : "?";
  let rows = CACHE.get(key);
  if (!rows) {
    rows = decode(key, ROWS[key] as string);
    CACHE.set(key, rows);
  }
  return rows;
}

/** Decode every glyph in the table; throws on a malformed one. */
export function checkTable(): number {
  for (const [key, pattern] of Object.entries(ROWS)) decode(key, pattern);
  return GLYPH_KEYS.length;
}
