[ "$EMPTY_STUB" != "$UNK_STUB" ] && [ "$EMPTY_TRACE" != "$UNK_TRACE" ] \
  && ok "8e empty and unknown produce DIFFERENT observable behaviour" \
  || bad "8e empty and unknown collapsed to the same path"

# A missing heimdall-wrap must never brick bare `hmd` (the class-4 landmine: a bare
# helper call under `set -euo pipefail` exits 127 and kills the whole launcher).
rm -f "$ROUTE_DIR/bin/heimdall-wrap"
run_hmd
grep -q 'launch:task' "$TRACE" \
  && ok "8f bare hmd survives a MISSING heimdall-wrap (degrades, never bricks)" \
  || bad "8f a missing heimdall-wrap bricked bare hmd" "trace=[$(cat "$TRACE")]"
route_stub heimdall-wrap

# ══════════════════════════════════════════════════════════════════════════════
# 9. SYNTAX
# ══════════════════════════════════════════════════════════════════════════════
echo
echo "9. syntax"
for f in "$BIN/heimdall" "$BIN/heimdall-wrap"; do
  if bash -n "$f" 2>/dev/null; then
    ok "9 $(basename "$f") passes bash -n"
  else
    bad "9 $(basename "$f") has syntax errors" "$(bash -n "$f" 2>&1 | head -3)"
  fi
done

# ── summary ───────────────────────────────────────────────────────────────────
echo
echo "--------------------------------------------------------------------"
printf 'wrap-lifecycle: %d passed, %d failed, %d skipped\n' "$PASS" "$FAIL" "$SKIP"
[ "$FAIL" -eq 0 ] || exit 1
