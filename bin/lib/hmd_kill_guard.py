#!/usr/bin/env python3
r"""hmd_kill_guard -- would this Bash command kill processes by NAME or by a COMPUTED pid?

2026-10-12 16:29Z: one agent, debugging a temp-repo test, ran `pkill -f heimdall-relay-client`. The pattern matched every relay
client on the machine -- the operator's two live phone clients included -- and a client answers SIGTERM by revoking its phone
pairing, so both phones were unpaired. A regex over the command text is walked around by quoting the name, `heimdall-rela[y]`,
a partial pattern, `pkill -f "$X"`, a pid looked up first, `xargs kill`, `sh -c`, `env`/`command`/`exec`, `kill -- -<pgid>`.
So this reads the command the way a shell does (quotes, escapes, substitutions, pipelines, heredocs, wrapper commands) and asks
one question of every simple command: does a kill verb run on a target nobody wrote down?

BEST-EFFORT DEFENSE IN DEPTH, NOT A SECURITY BOUNDARY. A text guard on shell can never be complete: bash grammar is far larger
than this file reads, and a command can build a verb or a script at run time. This catches the ways an agent really reaches for
(pkill, kill $(pgrep ...), xargs kill, sh -c, ...) and it fails CLOSED -- a command that mentions kill and that this cannot
fully read is denied -- but the protection that does not depend on reading shell is the client's own: a stray signal must not be
able to unpair a phone (a design decision still open with the operator). Do not lean on this file for that.

  denied   pkill / killall / skill with ANY pattern (a pattern is machine-wide and cannot be proven not to match a hmd server);
           kill whose target is not a literal pid number (a variable, a substitution, an xargs feed, a glob, a process group
           -N, 0, -1); `find -exec kill`; `fuser -k`; a kill verb run through sh -c, eval or a heredoc; a kill verb inside an
           awk / python / perl / node script; kill commands generated by one command and piped into a shell. Verbs are read in
           any case (a case-insensitive filesystem runs PKILL as pkill).
  allowed  kill [-SIGNAL | -s SIGNAL] <literal pid>...   kill $!   kill %N   kill -0 <anything> (sends nothing)   kill -l;
           reading (pgrep, ps, lsof, grep); text that only MENTIONS a verb (echo, grep, a commit message, a heredoc body)
  unread   denied while the command mentions kill: an unbalanced quote, substitution or brace; a heredoc it cannot follow to its
           end (or a << that is really a shift in arithmetic) or whose body the shell expands; $'...' and $[...]; a command name
           or shell string that is a bare variable or substitution ($K -f x, eval "$X", sh -c "$X"); shell strings nested more
           than 8 deep; an internal error or a timeout
  unseen   what no reading can see: a verb spelled out of pieces, a glob that expands to a verb, a python os.kill of a pid it
           looked up, a script file that kills

Protocol: the command text on stdin; stdout `ok` and exit 0 = nothing wrong; one reason line and exit 3 = deny. Anything else (a
crash, no output, another exit status) is NOT a clearance, and bin/heimdall-precheck-bash denies on it. A command that does not
mention kill (or fuser) is not this guard's business and gets `ok`. HMD_KILL_GUARD_TIMEOUT_S (default 5) bounds the run.
"""
import os
import re
import signal
import sys

ASSIGN = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*\+?=")
NAME = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
PID = re.compile(r"^[1-9][0-9]*$")
JOB = re.compile(r"^%([0-9]+|%|\+|-)?$")
SIGSPEC = re.compile(r"^-([0-9]+|[A-Za-z][A-Za-z0-9+-]*)$")
DURATION = re.compile(r"^[0-9.]+[smhd]?$")
LOOKUP = re.compile(r"^-[pVv]*[Vv][pVv]*$")
INTERP = re.compile(r"^(python[0-9.]*|perl|ruby|node|nodejs|osascript|php|lua|expect|tclsh|[a-z]*awk)$")
AWK = re.compile(r"^[a-z]*awk$")
KILL_VERB = re.compile(r"(?<![\w./-])(pkill|killall)(?![\w-])", re.I)
ANY_KILL = re.compile(r"(?<![\w./-])(pkill|killall|kill)(?![\w-])", re.I)
MENTION = re.compile(r"kill|fuser", re.I)

KILLERS = frozenset(("pkill", "killall", "skill", "killall5", "slay"))
KILLERS_AND_KILL = KILLERS | frozenset(("kill",))
SHELLS = frozenset(("sh", "bash", "zsh", "dash", "ksh", "ash", "mksh"))
RESERVED = frozenset(("if", "then", "else", "elif", "do", "while", "until", "!", "{", "}"))
SKIPPED = frozenset(("for", "select", "case", "function"))  # what follows is a name, not a command
REDIRS = ("<<<", "<<-", "<<", "<&", "<>", ">>", ">&", ">|", "<", ">")
MAX_DEPTH = 8
WRAPPERS = {  # command -> its options that take a separate argument
    "env": ("-u", "-C", "--unset", "--chdir"),
    "sudo": ("-u", "-g", "-C", "-h", "-p", "-r", "-t", "-T", "-U", "-D", "--user", "--group"),
    "doas": ("-u", "-C"),
    "nohup": (),
    "command": (),
    "builtin": (),
    "exec": ("-a",),
    "time": (),
    "nice": ("-n",),
    "ionice": ("-c", "-n", "-p"),
    "setsid": (),
    "stdbuf": ("-i", "-o", "-e"),
    "caffeinate": ("-t", "-w"),
    "timeout": ("-k", "-s", "--signal", "--kill-after"),
    "xargs": ("-n", "-I", "-P", "-L", "-s", "-E", "-d", "-a", "-J", "-R", "-S"),
}

try:
    TIMEOUT_S = float(os.environ.get("HMD_KILL_GUARD_TIMEOUT_S", "5"))
except ValueError:
    TIMEOUT_S = 5.0

# Reasons are fixed one-liners without quotes or backslashes: they are put into a JSON deny verbatim.
R_NAME = "pkill/killall kills by name or pattern, which is machine-wide"
R_PID = "kill with a target that is not a literal pid number (a variable, a substitution, an xargs feed or a glob)"
R_GROUP = "kill of a process group or another target that is not a plain pid (-N, 0, -1, a name)"
R_PIPE = "kill commands generated by one command and piped into a shell"
R_SCRIPT = "kill, pkill or killall inside an awk, python, perl or node script"
R_FUSER = "fuser -k kills whatever holds a file or a port"
R_OPAQUE = "a command name or shell string that is a bare variable or substitution, which the guard cannot read"
R_DEEP = "shell strings nested more than 8 deep, so the guard cannot read the command"
R_UNREAD = "the guard could not read this command (%s), so it is denied while it mentions kill"
U_QUOTE = "an unbalanced quote, substitution or brace, so the guard cannot read the command"
U_SYNTAX = ("shell syntax the guard does not read (a heredoc it cannot follow or whose body the shell expands, ANSI-C quoting, "
            "a substitution inside a parameter expansion, old-style arithmetic), so the guard cannot read the command")


class Word(object):
    """One shell word: text with quotes and escapes removed; dynamic when an expansion or glob makes its value unknowable;
    bgpid when it is exactly $!; op for a redirection operator."""
    __slots__ = ("text", "dynamic", "bgpid", "op")

    def __init__(self, text, dynamic=False, bgpid=False, op=False):
        self.text, self.dynamic, self.bgpid, self.op = text, dynamic, bgpid, op


class Cmd(object):
    """A simple command: its words, the heredoc / here-string bodies fed to it, the commands earlier in its pipeline."""
    __slots__ = ("words", "bodies", "upstream")

    def __init__(self, upstream=()):
        self.words, self.bodies, self.upstream = [], [], list(upstream)


class Lexer(object):
    """Splits command text into simple commands. Substitutions ($(...), backticks, <(...)) are lexed in place, so the commands
    inside them are commands like any other; heredoc bodies are data (they are handed to the command that reads them).
    Whatever it cannot read faithfully sets `unparsed` to a reason instead of guessing."""

    def __init__(self, text):
        self.s, self.n, self.i, self.cmds, self.unparsed = text, len(text), 0, [], None

    def flag(self, reason):
        if self.unparsed is None:
            self.unparsed = reason

    def heredoc_body(self, delim, tabs):
        """(the body, whether its terminator line was found); self.i is left after the terminator."""
        s, lines = self.s, []
        while self.i < self.n:
            j = s.find("\n", self.i)
            line = s[self.i:] if j < 0 else s[self.i:j]
            self.i = self.n if j < 0 else j + 1
            if (line.lstrip("\t") if tabs else line) == delim:
                return "\n".join(lines), True
            lines.append(line)
        return "\n".join(lines), False

    def braces(self, i):
        """s[i:i + 2] is '${': the index after its closing brace (a missing one, or a substitution inside, is flagged)."""
        s, depth, j = self.s, 1, i + 2
        while j < self.n:
            c = s[j]
            if c == "\\":
                j += 2
            elif c in "'\"":
                k = s.find(c, j + 1)
                j = self.n if k < 0 else k + 1
            else:
                depth += (c == "{") - (c == "}")
                j += 1
                if depth == 0:
                    if "$(" in s[i:j] or "`" in s[i:j]:
                        self.flag(U_SYNTAX)
                    return j
        self.flag(U_QUOTE)
        return self.n

    def expansion(self, i):
        """s[i] is '$': lex what it starts and return the index after it (i + 1 when it is a literal dollar)."""
        s = self.s
        nx = s[i + 1] if i + 1 < self.n else ""
        if nx == "(":
            self.i = i + 2
            self.commands(")")
            return self.i
        if nx == "{":
            return self.braces(i)
        if nx in ("'", "["):  # $'...' ANSI-C quoting and $[...] arithmetic are not decoded
            self.flag(U_SYNTAX)
            return i + 1
        m = NAME.match(s, i + 1)
        if m:
            return m.end()
        return i + 2 if nx and nx in "0123456789!@*#?$-" else i + 1

    def dquote(self):
        """self.i is at an opening double quote: (text, dynamic), with self.i left after the closing one."""
        s, i, out, dyn = self.s, self.i + 1, [], False
        while i < self.n:
            c = s[i]
            if c == '"':
                self.i = i + 1
                return "".join(out), dyn
            if c == "\\" and i + 1 < self.n:
                if s[i + 1] in '$`"\\':
                    out.append(s[i + 1])
                elif s[i + 1] != "\n":
                    out.append(s[i:i + 2])
                i += 2
            elif c == "$":
                j = self.expansion(i)
                out.append(s[i:j])
                dyn, i = dyn or j > i + 1, j
            elif c == "`":
                self.i = i + 1
                self.commands("`")
                out.append(s[i:self.i])
                dyn, i = True, self.i
            else:
                out.append(c)
                i += 1
        self.i = self.n
        self.flag(U_QUOTE)
        return "".join(out), dyn

    def commands(self, stop):
        """Lex simple commands into self.cmds until `stop` closes a substitution (None: to the end of the text)."""
        s, n = self.s, self.n
        cur = Cmd()
        word, start, dyn, brace, expect = None, 0, False, False, None
        pending, depth = [], 0

        def open_word(at):
            nonlocal word, start
            if word is None:
                word, start = [], at

        def close_word(end):
            nonlocal word, dyn, brace, expect
            if word is None:
                return
            text = "".join(word)
            cur.words.append(Word(text, dyn or (brace and text not in ("{", "}")), s[start:end] in ("$!", '"$!"')))
            if expect in ("<<", "<<-"):
                pending.append((text, expect == "<<-", cur, s[start:end] != text))  # last: the delimiter was quoted
            elif expect == "<<<":
                cur.bodies.append(text)
            word, dyn, brace, expect = None, False, False, None

        def end_cmd(end, piped=False):
            nonlocal cur
            close_word(end)
            nxt = Cmd(cur.upstream + [cur] if piped else ())
            if cur.words or cur.bodies:
                self.cmds.append(cur)
            cur = nxt

        def finish():
            if pending:  # a << whose body never began: a shift in arithmetic, or a heredoc with no body at all
                self.flag(U_SYNTAX)

        while self.i < n:
            i = self.i
            c = s[i]
            if c in " \t":
                close_word(i)
                self.i = i + 1
            elif c == "\n":
                end_cmd(i)
                self.i = i + 1
                for delim, tabs, owner, quoted in pending:
                    body, found = self.heredoc_body(delim, tabs)
                    owner.bodies.append(body)
                    if not found or (not quoted and ("$(" in body or "`" in body)):
                        self.flag(U_SYNTAX)  # no terminator, or a body the shell expands (and so runs)
                del pending[:]
            elif c == "#" and word is None:
                j = s.find("\n", i)
                self.i = n if j < 0 else j
            elif c == "\\":
                if s.startswith("\n", i + 1):
                    self.i = i + 2
                else:
                    open_word(i)
                    word.append(s[i + 1:i + 2])
                    self.i = i + 2
            elif c == "'":
                open_word(i)
                j = s.find("'", i + 1)
                if j < 0:
                    self.flag(U_QUOTE)
                word.append(s[i + 1:] if j < 0 else s[i + 1:j])
                self.i = n if j < 0 else j + 1
            elif c == '"':
                open_word(i)
                text, d = self.dquote()
                word.append(text)
                dyn = dyn or d
            elif c == "`":
                if stop == "`":
                    end_cmd(i)
                    self.i = i + 1
                    finish()
                    return
                open_word(i)
                self.i = i + 1
                self.commands("`")
                word.append(s[i:self.i])
                dyn = True
            elif c == "$":
                j = self.expansion(i)
                open_word(i)
                word.append(s[i:j])
                dyn = dyn or j > i + 1
                self.i = j
            elif c == ";":
                end_cmd(i)
                self.i = i + 1
            elif c == "&":
                if s.startswith("&>", i):
                    close_word(i)
                    op = "&>>" if s.startswith("&>>", i) else "&>"
                    cur.words.append(Word(op, op=True))
                    self.i = i + len(op)
                else:
                    end_cmd(i)
                    self.i = i + (2 if s.startswith("&&", i) else 1)
            elif c == "|":
                if s.startswith("||", i):
                    end_cmd(i)
                    self.i = i + 2
                else:
                    end_cmd(i, piped=True)
                    self.i = i + (2 if s.startswith("|&", i) else 1)
            elif c == "(":
                end_cmd(i)
                depth += 1
                self.i = i + 1
            elif c == ")":
                end_cmd(i)
                self.i = i + 1
                if depth:
                    depth -= 1
                elif stop == ")":
                    finish()
                    return
            elif c in "<>":
                if word is not None and not dyn and "".join(word).isdigit():
                    word = None  # `2>file`: the digits name a descriptor, not an argument
                else:
                    close_word(i)
                if s.startswith("(", i + 1):  # <(cmd) and >(cmd)
                    open_word(i)
                    self.i = i + 2
                    self.commands(")")
                    word.append(s[i:self.i])
                    dyn = True
                else:
                    op = next(o for o in REDIRS if s.startswith(o, i))
                    cur.words.append(Word(op, op=True))
                    if op in ("<<", "<<-", "<<<"):
                        expect = op
                    self.i = i + len(op)
            else:
                open_word(i)
                word.append(c)
                if c in "*?[":
                    dyn = True
                elif c == "{":
                    brace = True
                self.i = i + 1
        end_cmd(n)
        finish()
        if stop is not None:
            self.flag(U_QUOTE)  # ran off the end of the text without the closing parenthesis or backtick


def lex(text):
    """(the simple commands in text, the reason it could not be read faithfully or None)."""
    lexer = Lexer(text)
    lexer.commands(None)
    return lexer.cmds, lexer.unparsed


def plain(words):
    """A command's words without its redirections and their targets."""
    out, skip = [], False
    for w in words:
        if skip:
            skip = False
        elif w.op:
            skip = True
        else:
            out.append(w)
    return out


def opaque(word, command=False):
    """A word that starts with an expansion ($K, "$X", $(cmd), `cmd`): what it names or runs cannot be read. As a command name
    one with a slash ($HOME/bin/tool) is a path, not a verb held in a variable."""
    return word.dynamic and word.text[:1] in ("$", "`") and not (command and "/" in word.text)


def skip_options(base, args):
    """`args` after the wrapper `base` has taken its own options (and env's assignments, timeout's duration)."""
    takes, k = WRAPPERS[base], 0
    while k < len(args):
        t = args[k].text
        if t == "--":
            k += 1
            break
        if base == "env" and ASSIGN.match(t):
            k += 1
        elif t.startswith("-") and len(t) > 1:
            k += 2 if t in takes else 1
        else:
            break
    rest = args[k:]
    if base == "timeout" and rest and DURATION.match(rest[0].text):
        rest = rest[1:]
    return rest


def unwrap(words):
    """(the words of the command that actually runs, whether xargs feeds it): leading assignments, reserved words and wrapper
    commands (env, sudo, timeout, xargs, ...) are skipped."""
    args, via_xargs = plain(words), False
    while args:
        t = args[0].text
        base = os.path.basename(t).lower()
        if ASSIGN.match(t) or (not args[0].dynamic and t in RESERVED):  # FOO=$(...) pkill ... runs pkill
            args = args[1:]
        elif args[0].dynamic:
            break
        elif base in SKIPPED:
            return [], via_xargs
        elif base in WRAPPERS:
            if base == "command" and len(args) > 1 and LOOKUP.match(args[1].text):
                return [], via_xargs  # `command -v pkill` only looks the name up
            via_xargs = via_xargs or base == "xargs"
            args = skip_options(base, args[1:])
        else:
            break
    return args, via_xargs


def check_kill(rest):
    """The words after `kill`: only a literal pid (or $!, or a job spec) may be a target."""
    k = 0
    if rest and not rest[0].dynamic:
        t = rest[0].text
        if t in ("-l", "-L", "-0"):
            return None  # list the signals / send nothing
        if t in ("-s", "-n"):
            if len(rest) > 1 and rest[1].text == "0":
                return None
            k = 2
        elif t == "--" or SIGSPEC.match(t):
            k = 1
    if k < len(rest) and not rest[k].dynamic and rest[k].text == "--":
        k += 1
    for w in rest[k:]:
        if w.bgpid or (not w.dynamic and (PID.match(w.text) or JOB.match(w.text))):
            continue
        return R_PID if w.dynamic else R_GROUP
    return None


def check_find(rest):
    for k, w in enumerate(rest[:-1]):
        if w.text in ("-exec", "-execdir", "-ok", "-okdir"):
            args, _ = unwrap(rest[k + 1:])
            if args and not args[0].dynamic and os.path.basename(args[0].text).lower() in KILLERS_AND_KILL:
                return R_PID
    return None


def check_shell(cmd, rest, depth):
    """sh/bash/...: the -c string, a heredoc or here-string fed to it, or kill commands piped into it are read as commands."""
    script, k = None, 0
    while k < len(rest) and not rest[k].dynamic:
        t = rest[k].text
        if t == "--":
            k += 1
            break
        if not t.startswith(("-", "+")) or t in ("-", "+"):
            break
        if t in ("-o", "+o", "-O", "+O"):
            k += 2
        elif t.startswith("-") and not t.startswith("--") and "c" in t[1:]:
            if k + 1 < len(rest):
                if opaque(rest[k + 1]):
                    return R_OPAQUE
                script = rest[k + 1].text
            break
        else:
            k += 1
    for source in ([script] if script is not None else []) + cmd.bodies:
        why = analyze(source, depth + 1)
        if why:
            return why
    if script is None and not cmd.bodies and k >= len(rest):  # a shell reading its commands from a pipe
        if any("kill" in w.text.lower() for up in cmd.upstream for w in up.words):
            return R_PIPE
    return None


def check(cmd, depth):
    args, via_xargs = unwrap(cmd.words)
    if not args:
        return None
    head = args[0]
    base, rest = os.path.basename(head.text).lower(), args[1:]
    if head.dynamic:
        if base in KILLERS:  # "$BIN"/pkill
            return R_NAME
        return R_OPAQUE if opaque(head, command=True) else None
    if base in KILLERS:
        return R_NAME
    if base == "kill":
        return R_PID if via_xargs else check_kill(rest)
    if base == "fuser":
        if any(w.text.startswith("-") and not w.text.startswith("--") and "k" in w.text[1:] for w in rest):
            return R_FUSER
        return None
    if base == "find":
        return check_find(rest)
    if base in SHELLS:
        return check_shell(cmd, rest, depth)
    if base == "eval":
        if rest and opaque(rest[0]):
            return R_OPAQUE
        return analyze(" ".join(w.text for w in rest), depth + 1)
    if INTERP.match(base):
        pat = ANY_KILL if AWK.match(base) else KILL_VERB
        if any(pat.search(t) for t in [w.text for w in rest] + cmd.bodies):
            return R_SCRIPT
    return None


def analyze(text, depth=0):
    """The reason this command text must be denied, or None. Something it found wins over something it could not read."""
    if depth > MAX_DEPTH:
        return R_DEEP
    cmds, unparsed = lex(text)
    for cmd in cmds:
        why = check(cmd, depth)
        if why:
            return why
    return unparsed


def verdict(text):
    """analyze(), but only for a command that mentions kill or fuser (quotes and backslashes removed, any case, as the hook's
    own test does): any other command is not this guard's business."""
    if not MENTION.search(re.sub(r"[\\'\"]", "", text)):
        return None
    return analyze(text)


class GuardTimeout(Exception):
    """The guard used up its run-time budget (HMD_KILL_GUARD_TIMEOUT_S) before it finished reading the command."""


def _timed_out(signum, frame):
    raise GuardTimeout()


def arm(seconds):
    """Start the run-time budget (0 cancels it); a platform without setitimer runs unbounded rather than not at all."""
    if hasattr(signal, "setitimer"):
        signal.signal(signal.SIGALRM, _timed_out)
        signal.setitimer(signal.ITIMER_REAL, seconds)


def main():
    arm(TIMEOUT_S)
    try:
        why = verdict(sys.stdin.buffer.read().decode("utf-8", "replace"))
    except Exception as exc:  # a command this could not read is a command it cannot vouch for: deny it
        why = R_UNREAD % type(exc).__name__
    arm(0)
    if why:
        sys.stdout.write(why + "\n")
        return 3
    sys.stdout.write("ok\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
